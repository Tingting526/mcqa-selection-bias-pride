#!/usr/bin/env python3
"""Build RQ1 presentation from frozen endpoints and published Table 3 cells.

No scoring, model inference, evaluation-formula or population changes. Original
means use all twenty one-decimal published rows, current means all six unrounded
verified rows. Decimal arithmetic avoids rounding artifacts in the summaries.
"""
from pathlib import Path
from decimal import Decimal, ROUND_HALF_UP
import csv
import hashlib
import json

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT/'analysis/outputs/rq1_restructure_20261021'
CURRENT = ROOT/'analysis/outputs/phase3b_20261018/verified/tables/rq1_reproduction.csv'
PUBLISHED = OUT/'sources/published_table3_0shot.csv'
NAMES = dict(mmlu='MMLU', arc='ARC-Challenge', csqa='CommonsenseQA')
MODELS = dict(zip(('llama-3.1-8b-instruct','qwen2.5-7b-instruct','gemma-2-9b-it',
    'mistral-7b-instruct-v0.3','qwen3-8b','glm-4-9b-chat-hf'),
    ('Llama 3.1 8B','Qwen2.5 7B','Gemma 2 9B','Mistral 7B v0.3','Qwen3 8B','GLM 4 9B')))
D = Decimal


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def fmt(value, signed=False):
    value = D(value).quantize(D('.01'), rounding=ROUND_HALF_UP)
    if value == 0: value = abs(value)
    return format(value, '+.2f' if signed else '.2f')


def mean(group, key):
    return sum(D(row[key]) for row in group)/D(len(group))


def table(filename, caption, label, columns, header, rows):
    text = ('% Generated by analysis/scripts/restructure_rq1_presentation.py.\n'
        + r'\begin{table}[htbp]'+'\n'+r'\centering\small\setlength{\tabcolsep}{4pt}'+'\n'
        + r'\caption{'+caption+'}\n'+r'\label{'+label+'}\n'
        + r'\begin{tabular}{'+columns+'}\n'+r'\toprule'+'\n'+header+r'\\'+'\n'
        + r'\midrule'+'\n'+'\n'.join(rows)+'\n'+r'\bottomrule'+'\n'
        + r'\end{tabular}'+'\n'+r'\end{table}'+'\n')
    (ROOT/'Paper/generated'/filename).write_text(text)
    return dict(path='Paper/generated/'+filename, sha256=sha(ROOT/'Paper/generated'/filename))


def main():
    current = list(csv.DictReader(CURRENT.open()))
    published = list(csv.DictReader(PUBLISHED.open()))
    assert len(current) == 18 and len(published) == 60
    summaries, sources, model_rows = [], [], []
    original_models = None
    for dataset in NAMES:
        a = [row for row in current if row['benchmark'] == dataset]
        b = [row for row in published if row['benchmark'] == dataset]
        assert len(a) == 6 and {r['model'] for r in a} == set(MODELS)
        assert len(b) == len({r['model'] for r in b}) == 20
        assert all(r['verification_status'] == 'verified_from_matching_raw_observations' for r in a)
        if original_models is None: original_models = [r['model'] for r in b]
        assert [r['model'] for r in b] == original_models
        for panel, group in [('Zheng',b),('Current',a)]:
            baseline_a, baseline_r = mean(group,'default_accuracy_percent'), mean(group,'default_rstd_pp')
            for method in ('default','cpa','pride'):
                prefix = 'pride_hybrid' if method == 'pride' and panel == 'Current' else method
                accuracy, rstd = mean(group,prefix+'_accuracy_percent'), mean(group,prefix+'_rstd_pp')
                summaries.append(dict(benchmark=dataset,panel=panel,n_models=len(group),method=method,
                    accuracy_mean=str(accuracy),rstd_mean=str(rstd),
                    accuracy_change_pp=str(accuracy-baseline_a),rstd_change_pp=str(rstd-baseline_r),
                    default_rstd_min=str(min(D(r['default_rstd_pp']) for r in group)),
                    default_rstd_max=str(max(D(r['default_rstd_pp']) for r in group))))

    # 5.1.1: only Default, grouped horizontally by benchmark.
    rows = []
    for model,name in MODELS.items():
        vals = []
        for dataset in NAMES:
            row = next(r for r in current if (r['model'],r['benchmark']) == (model,dataset))
            vals += [fmt(row['default_accuracy_percent']),fmt(row['default_rstd_pp'])]
        rows.append(name+' & '+' & '.join(vals)+r'\\')
    sources.append(table('rq1_default_overview.tex',
        r'Uncorrected Default results for the six models under raw-text zero-shot scoring. A is accuracy (\%) and R original RStd (pp). Retained populations: MMLU $N=13,592$, ARC-Challenge $N=1,165$, CommonsenseQA $N=1,216$.',
        'tab:rq1-default-overview','lrrrrrr',
        r'Model & \multicolumn{2}{c}{MMLU} & \multicolumn{2}{c}{ARC-Challenge} & \multicolumn{2}{c}{CommonsenseQA}\\'+'\n'+r'\cmidrule(lr){2-3}\cmidrule(lr){4-5}\cmidrule(lr){6-7}'+'\n'+r' & A & R & A & R & A & R',rows))
    rows = []
    for dataset,name in NAMES.items():
        for i,panel in enumerate(('Zheng','Current')):
            r = next(x for x in summaries if (x['benchmark'],x['panel'],x['method']) == (dataset,panel,'default'))
            rows.append((name if i == 0 else '')+' & '+panel+f" ({r['n_models']})"+' & '
                +' & '.join(fmt(r[k]) for k in ('accuracy_mean','rstd_mean','default_rstd_min','default_rstd_max'))+r'\\')
        if dataset != 'csqa': rows.append(r'\addlinespace[3pt]')
    sources.append(table('rq1_default_panel_comparison.tex',
        r'Default panel summaries before correction. A is unweighted mean accuracy (\%); R is original RStd (pp). Zheng: all twenty model rows in Table~3, p.~22 \citep{zheng2024robust}; Current: all six verified models. Original means use the published one-decimal cells; current means use unrounded endpoints.',
        'tab:rq1-default-panels','llrrrr',r'Benchmark & Panel ($n$) & Mean A & Mean R & Min R & Max R',rows))

    # 5.1.2: retain every CPA and PriDe endpoint, remove repeated Default columns.
    for dataset,name in NAMES.items():
        selected = [r for r in current if r['benchmark'] == dataset]
        rows = []
        for model,label in MODELS.items():
            r = next(x for x in selected if x['model'] == model)
            keys = ('cpa_accuracy_percent','cpa_rstd_pp','pride_hybrid_accuracy_percent','pride_hybrid_rstd_pp')
            rows.append(label+' & '+' & '.join(fmt(r[k]) for k in keys)+r'\\')
            for method,prefix in (('default','default'),('cpa','cpa'),('pride','pride_hybrid')):
                model_rows.append(dict(benchmark=dataset,model=model,method=method,
                    accuracy=r[prefix+'_accuracy_percent'],rstd=r[prefix+'_rstd_pp']))
        sources.append(table('results_'+dataset+'.tex',
            name+f" ($N={int(selected[0]['n']):,}$), raw-text zero-shot scoring after debiasing. A is accuracy (\\%), R original RStd (pp). PriDe (5\\%) is the five-draw mean full-population endpoint defined in Section~\\ref{{sec:pride-indomain}}.",
            'tab:results-pride-'+dataset,'lrrrr',
            r'Model & \multicolumn{2}{c}{CPA} & \multicolumn{2}{c}{PriDe (5\%)}\\'+'\n'+r'\cmidrule(lr){2-3}\cmidrule(lr){4-5}'+'\n'+r' & A & R & A & R',rows))

    rows = []
    for dataset,name in NAMES.items():
        for i,panel in enumerate(('Zheng','Current')):
            for j,method in enumerate(('cpa','pride')):
                r = next(x for x in summaries if (x['benchmark'],x['panel'],x['method']) == (dataset,panel,method))
                rows.append((name if i == j == 0 else '')+' & '+(panel+f" ({r['n_models']})" if j == 0 else '')
                    +' & '+('CPA' if method == 'cpa' else r'PriDe (5\%)')+' & '
                    +fmt(r['accuracy_mean'])+' & $'+fmt(r['accuracy_change_pp'],True)+'$ & '
                    +fmt(r['rstd_mean'])+' & $'+fmt(r['rstd_change_pp'],True)+'$'+r'\\')
        if dataset != 'csqa': rows.append(r'\addlinespace[4pt]')
    sources.append(table('rq1_zheng_comparison.tex',
        r'Absolute post-debiasing means and changes from Default. A is accuracy (\%); R is original RStd (pp); both $\Delta$ columns are pp. Models receive equal weight. Zheng means use published rounded model cells \citep[Table~3, p.~22]{zheng2024robust}; Appendix~\ref{app:rq1-published-changes} retains the separately reported $\Delta$ Average values.',
        'tab:rq1-zheng-comparison','lllrrrr',r'Benchmark & Panel ($n$) & Method & A & $\Delta A$ & R & $\Delta R$',rows))
    deltas = list(csv.DictReader((OUT/'sources/published_delta_average.csv').open()))
    assert len(deltas) == 6
    rows = []
    for r in deltas:
        method = 'CPA' if r['method'] == 'cpa' else r'PriDe (5\%)'
        rows.append(NAMES[r['benchmark']]+' & '+method+' & $'+format(D(r['accuracy_change_pp']),'+.1f')+'$ & $'+format(D(r['rstd_change_pp']),'+.1f')+'$'+r'\\')
    sources.append(table('rq1_published_changes.tex',
        r'Published twenty-model $\Delta$ Average cells from \citet[Table~3, p.~22]{zheng2024robust}, retaining their original one-decimal precision. Changes from Default are in pp: accuracy ($\Delta A$) and original RStd ($\Delta R$). These are the source\textquotesingle s reported changes, rather than recalculations from its rounded model rows.',
        'tab:rq1-published-changes','llrr',r'Benchmark & Method & $\Delta A$ & $\Delta R$',rows))
    for filename, records in [('panel_summaries.csv',summaries),('current_model_endpoints.csv',model_rows)]:
        with (OUT/filename).open('w') as stream:
            writer=csv.DictWriter(stream,fieldnames=list(records[0]));writer.writeheader();writer.writerows(records)
    provenance = dict(version='rq1-presentation-v2',inference_executed=False,
        current_source=str(CURRENT.relative_to(ROOT)),current_sha256=sha(CURRENT),
        original_source='ICLR 2024 final paper, Table 3, printed p. 22, 0-shot',
        original_pdf_url='https://proceedings.iclr.cc/paper_files/paper/2024/file/54dd9e0cff6d9214e20d97eb2a3bae49-Paper-Conference.pdf',
        original_pdf_sha256=sha(OUT/'sources/zheng_iclr2024.pdf'),
        extracted_cells_sha256=sha(PUBLISHED),original_models=original_models,current_models=list(MODELS),
        model_counts_per_benchmark=dict(Zheng=20,Current=6),
        aggregation='unweighted mean over all model rows; no family matching or model subsetting',
        rounding='two decimal places, Decimal ROUND_HALF_UP; published input cells have one-decimal precision',
        original_rstd='population SD of original gold-label recalls in percent; np.std default ddof=0',
        prior_reference_code='2ae2f40c77006f7a00a4675bdfb30151c2406691/code/debias_pride.py, lines 113-168',
        generated_files=sources)
    (OUT/'comparison_provenance.json').write_text(json.dumps(provenance,indent=2)+'\n')
    print(json.dumps(dict(tables=len(sources),original_models_per_benchmark=20,current_models_per_benchmark=6,inference_executed=False)))


if __name__ == '__main__': main()
