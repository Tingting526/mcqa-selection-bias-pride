#!/usr/bin/env python3
"""Generate compact supplementary tables from the review-response analyses."""
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "analysis/outputs/thesis_strengthening_20261021"
GENERATED = ROOT / "Paper/generated"
NAMES = dict(zip(["llama-3.1-8b-instruct", "qwen2.5-7b-instruct", "gemma-2-9b-it",
                 "mistral-7b-instruct-v0.3", "qwen3-8b", "glm-4-9b-chat-hf"],
                ["Llama 3.1 8B", "Qwen2.5 7B", "Gemma 2 9B", "Mistral 7B v0.3", "Qwen3 8B", "GLM 4 9B"]))


def table(name, caption, label, header, rows, columns):
    text = ("% Generated by analysis/scripts/build_strengthening_tables.py.\n"
            + r"\begin{table}[htbp]" + "\n" + r"\centering\small\setlength{\tabcolsep}{4pt}" + "\n"
            + r"\caption{" + caption + "}\n" + r"\label{" + label + "}\n"
            + r"\begin{tabular}{" + columns + "}\n" + r"\toprule" + "\n"
            + header + r"\\" + "\n" + r"\midrule" + "\n"
            + "\n".join(" & ".join(str(v) for v in row)+r"\\" for row in rows)
            + "\n" + r"\bottomrule" + "\n" + r"\end{tabular}" + "\n" + r"\end{table}" + "\n")
    (GENERATED / name).write_text(text)


def main():
    data = json.loads((OUT / "analysis_results.json").read_text())
    rows = []
    for row in data["arc"]:
        if "full" not in row: continue
        cells = [NAMES[row["model"]]]
        for key in ("consistency_percent", "accuracy_range_pp", "aggregation_accuracy_percent"):
            cells.extend(f"{row[condition][key]:.2f}" for condition in ("cyclic", "full"))
        rows.append(cells)
    table("strengthening_arc.tex", r"ARC-Challenge on the same 1,165 questions: four cyclic orderings (4) versus all 24 orderings (24). C is content consistency (\%), range is the accuracy range (pp), and A is accuracy after probability averaging (\%). Agreement across 24 orderings is a stricter criterion. Mistral has only four cached orderings.",
          "tab:arc-full", r"Model & $C_4$ & $C_{24}$ & Range$_4$ & Range$_{24}$ & $A_4$ & $A_{24}$", rows, "lrrrrrr")
    rows = []
    for model, name in NAMES.items():
        s, m = [next(row for row in data["subgroups"] if row["model"] == model and row["group"] == group)
                for group in ("single", "multi")]
        rows.append([name, *[f"{r['consistency_percent']:.2f}" for r in (s, m)],
                     *[f"${r['hybrid_minus_default_accuracy_pp']:+.2f}$" for r in (s, m)],
                     *[f"{r['cyclic_rstd_pp']:.2f}" for r in (s, m)]])
    table("strengthening_subgroups.tex", r"MedMCQA by released choice type: single (S, $N=2,801$) and multi (M, $N=1,140$). C is uncorrected content consistency (\%); $\Delta A$ is five-draw hybrid PriDe minus Default accuracy (pp); R is cyclic RStd (pp). Predictions use the original benchmark-wide calibration draws, with no subgroup prior fitting.",
          "tab:medmcqa-choice-type", r"Model & $C_S$ & $C_M$ & $\Delta A_S$ & $\Delta A_M$ & $R_S$ & $R_M$", rows, "lrrrrrr")
    rows = []
    for model, name in NAMES.items():
        f, r = [next(row for row in data["transfer"] if row["model"] == model and row["source"] == source)
                for source in ("medqa", "medmcqa")]
        rows.append([name, f"{f['prior_total_variation']:.3f}", f"{f['predictions_changed_percent']:.2f}",
                     f"{f['correct_gained_n']}/{f['correct_lost_n']}", f"{r['predictions_changed_percent']:.2f}",
                     f"{r['correct_gained_n']}/{r['correct_lost_n']}"])
    table("strengthening_transfer.tex", r"Transfer relative to in-domain PriDe on the primary target holdouts. TV is total variation between the two priors (probability units), identical in both directions. Switches are percentages of target questions; G/L counts wrong-to-correct/correct-to-wrong changes. Forward (F): MedQA to MedMCQA, $n=3,744$. Reverse (R): MedMCQA to MedQA, $n=1,210$.",
          "tab:transfer-explanation", r"Model & TV & Switches F & G/L F & Switches R & G/L R", rows, "lrrrrr")
    lengths = json.loads((OUT / "medical_token_lengths.json").read_text())
    rows = []
    for model, name in NAMES.items():
        rr = [row for row in lengths if row["model"] == model and "dataset" in row]
        rows.append([name, *[str(next(row for row in rr if row["dataset"] == ds)["max_tokens"])
                            if rr else "--" for ds in ("medqa", "medmcqa")], "0 / 0" if rr else "--"])
    table("strengthening_token_lengths.tex", r"Maximum reconstructed medical prompt lengths across all four cyclic shifts, with all six pinned tokenizers. The last column counts questions exceeding 1,536 tokens on MedQA/MedMCQA. Each tokenizer covers all 1,273/3,941 questions. Reconstruction does not certify the historical loaded tokenizer bytes.",
          "tab:medical-token-lengths", r"Model & MedQA max & MedMCQA max & Above cap", rows, "lrrr")

    # Editorial caption update only: retain every existing tabular cell verbatim.
    for ds in ("mmlu", "arc", "csqa", "medqa", "medmcqa"):
        path = GENERATED / f"results_{ds}.tex"
        text = path.read_text()
        text = text.replace(" Original numerical values are preserved.", "")
        path.write_text(text)

    path = GENERATED / "rq1_zheng_comparison.tex"
    text = path.read_text()
    caption = (r"Mean changes from each study's Default, in pp: accuracy ($\Delta A$) and original RStd ($\Delta R$). "
               r"Zheng's published twenty-model means \citep[Table 3, p.~22]{zheng2024robust} are compared with unweighted means for our six models. "
               r"Both use 5\% hybrid PriDe; the model panels differ and the original MMLU mean includes a smaller GPT-3.5 subset.")
    if "restructure_rq1_presentation.py" not in text.splitlines()[0]:
        start, end = text.index(r"\caption{"), text.index("\n\\label{")
        path.write_text(text[:start] + r"\caption{" + caption + "}" + text[end:])
    print("Generated four supplementary tables and applied legacy caption cleanup; numerical cells unchanged.")
    gpu_path = OUT / "gpu_sensitivity_results.json"
    if gpu_path.exists():
        gpu = json.loads(gpu_path.read_text())["results"]
        rows = []
        for model, name in NAMES.items():
            r = next(row for row in gpu if row["model"] == model and row["dataset"] == "mmlu")
            rows.append([name, *[f"${r[method+'_accuracy_change_pp']:+.3f}$" for method in ("default", "cyclic_perm", "pride")],
                         f"${r['pride_rstd_change_pp']:+.4f}$"])
        table("strengthening_mmlu_repair.tex", r"Literal MMLU inputs minus the primary inputs, on all 13,592 questions. Changes are in pp for Default, CPA and hybrid PriDe accuracy ($\Delta A$), and hybrid original RStd ($\Delta R_H$). The ten corrected questions replace their cached cycles; every prior is refitted on its original calibration IDs. Twelve old-input controls per model check scorer agreement.",
              "tab:mmlu-repair", r"Model & $\Delta A_D$ & $\Delta A_{CPA}$ & $\Delta A_H$ & $\Delta R_H$", rows, "lrrrr")
        rows = []
        for dataset, label in (("medqa", "MedQA"), ("medmcqa", "MedMCQA")):
            for j, (model, name) in enumerate(NAMES.items()):
                r = next(row for row in gpu if row["model"] == model and row["dataset"] == dataset)
                rows.append([name if j else r"\multicolumn{8}{l}{\textit{"+label+r"}}\\"+"\n"+name,
                             f"{r['default_accuracy_new']:.2f}", f"${r['default_accuracy_change_pp']:+.2f}$",
                             f"{r['consistency_percent_new']:.2f}", f"${r['consistency_percent_change_pp']:+.2f}$",
                             f"{r['cyclic_rstd_pp_new']:.2f}", f"${r['hybrid_minus_default_raw_pp']:+.2f}$",
                             f"${r['hybrid_minus_default_new_pp']:+.2f}$"])
        table("strengthening_native_chat.tex", r"Native-template medical scoring on the same 1,273 MedQA and 3,941 MedMCQA questions. A and C are native Default accuracy and content consistency (\%); $\Delta$ is native minus raw (pp). R is native cyclic RStd (pp). The last columns give hybrid PriDe minus Default accuracy under raw (H$_r$) and native (H$_n$) input, after fitting each condition on identical calibration IDs. Qwen3 uses its non-thinking template. These remain first-token scores.",
              "tab:native-chat", r"Model & A & $\Delta A$ & C & $\Delta C$ & R & H$_r$ & H$_n$", rows, "lrrrrrrr")
        print("Generated two verified GPU sensitivity tables.")


if __name__ == "__main__": main()
